public class ex_5_desenhoEstrelas {
    static void main() {
        for (int i =1; i<6; i++){

            if (i == 1){
                System.out.println("*   ");
            }
            if (i == 2){
                System.out.println("**   ");
            }
            if (i == 3){
                System.out.println("***  ");
            }
            if (i == 4){
                System.out.println("**** ");
            }
            if (i == 5){
                System.out.println("*****");
            }
        }
    }
}
